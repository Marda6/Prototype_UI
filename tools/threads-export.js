/* Thread libraries for the prototype's thread library window (packages/project/threads.js).
   Reads ENCY's sample libraries — SQLite files, table ISTThreadAccessor — and adds a Unified inch
   library (not among ENCY's samples) built from ASME B1.1 sizes; writes packages/project/threads-data.js.

     node tools/threads-export.js ["<ENCY data>/Libraries/Threads/Examples"]

   Node 22+ (node:sqlite). A library's title is its file name, as ENCY's window shows it ("Threads").
   Tap drill is not stored by ENCY: a 60° metric library gets major − pitch, the inch one the standard
   drill chart; 55° pipe threads get none (the window hides the column). */
const fs = require('fs'), path = require('path');
const {DatabaseSync} = require('node:sqlite');

const SRC = process.argv[2] || 'C:/ProgramData/Ency Software/Ency NB/Version 3/Libraries/Threads/Examples';
const OUT = path.join(__dirname, '..', 'packages', 'project', 'threads-data.js');
const ORDER = ['ISO metric screw thread', 'Threads', 'Cylindrical pipe thread, external',
  'Cylindrical pipe thread, internal', 'Compression HKT threads'];

const r = (x, d) => Math.round(x * 10 ** d) / 10 ** d;
const libs = [];

/* ---- Unified inch: sizes with UNC / UNF / UNEF (TPI, tap drill from the chart), then numbered sizes ---- */
const UN = [
  ['1/4', [20, .2010], [28, .2130], [32, .2188]], ['5/16', [18, .2570], [24, .2720], [32, .2812]],
  ['3/8', [16, .3125], [24, .3320], [32, .3438]], ['7/16', [14, .3680], [20, .3906], [28, .4040]],
  ['1/2', [13, .4219], [20, .4531], [28, .4688]], ['9/16', [12, .4844], [18, .5156], [24, .5156]],
  ['5/8', [11, .5312], [18, .5781], [24, .5781]], ['11/16', null, null, [24, .6406]],
  ['3/4', [10, .6562], [16, .6875], [20, .7031]], ['13/16', null, null, [20, .7656]],
  ['7/8', [9, .7656], [14, .8125], [20, .8281]], ['15/16', null, null, [20, .8906]],
  ['1', [8, .8750], [12, .9219], [20, .9531]], ['1-1/16', null, null, [18, 1.0000]],
  ['1-1/8', [7, .9844], [12, 1.0469], [18, 1.0781]], ['1-3/16', null, null, [18, 1.1406]],
  ['1-1/4', [7, 1.1094], [12, 1.1719], [18, 1.1875]], ['1-5/16', null, null, [18, 1.2656]],
  ['1-3/8', [6, 1.2188], [12, 1.2969], [18, 1.3125]], ['1-7/16', null, null, [18, 1.3750]],
  ['1-1/2', [6, 1.3438], [12, 1.4219], [18, 1.4531]], ['1-9/16', null, null, [18, 1.5000]],
  ['1-5/8', null, null, [18, 1.5625]], ['1-11/16', null, null, [18, 1.6250]],
  ['1-3/4', [5, 1.5625], null, null], ['2', [4.5, 1.7812], null, null]
];
const NUM = [['#2', 56, 'UNC', .0700], ['#2', 64, 'UNF', .0700], ['#4', 40, 'UNC', .0890], ['#4', 48, 'UNF', .0935],
  ['#5', 40, 'UNC', .1015], ['#5', 44, 'UNF', .1040], ['#6', 32, 'UNC', .1065], ['#6', 40, 'UNF', .1130],
  ['#8', 32, 'UNC', .1360], ['#8', 36, 'UNF', .1360], ['#10', 24, 'UNC', .1495], ['#10', 32, 'UNF', .1590],
  ['#12', 24, 'UNC', .1770], ['#12', 28, 'UNF', .1820], ['#12', 32, 'UNEF', .1850]];
function frac(s){ return s.split('-').reduce((a, p) => a + (p.includes('/') ? p.split('/')[0] / p.split('/')[1] : +p), 0); }
const unRows = [];
const minor = (d, n) => r(d - 1.082532 / n, 4);
UN.forEach(([size, ...ser]) => ser.forEach((s, i) => {
  if(!s) return;
  const d = frac(size), n = s[0];
  unRows.push([size + '-' + n + ' ' + ['UNC', 'UNF', 'UNEF'][i], r(d, 4), minor(d, n), n, s[1]]);
}));
NUM.forEach(([no, n, ser, tap]) => {
  const d = .060 + .013 * +no.slice(1);
  unRows.push([no + '-' + n + ' ' + ser, r(d, 4), minor(d, n), n, tap]);
});
libs.push({id:'un', name:'Unified inch screw thread', unit:'in', pitch:'tpi', angle:60, incl:30, taper:0, starts:1, tap:true, rows:unRows});

/* ---- ENCY's sample libraries ---- */
const files = fs.readdirSync(SRC).filter(f => f.endsWith('.db'))
  .sort((a, b) => ORDER.indexOf(a.slice(0, -3)) - ORDER.indexOf(b.slice(0, -3)));
for(const f of files){
  const db = new DatabaseSync(path.join(SRC, f), {readOnly:true});
  const h = db.prepare('select * from ISTHeaderAccess').get();
  const rows = db.prepare('select * from ISTThreadAccessor order by object_id').all();
  db.close();
  const one = k => { const s = new Set(rows.map(x => x[k])); if(s.size > 1) console.warn(f, k, 'varies:', [...s]); return rows[0][k]; };
  const angle = one('ANGLE'), incl = one('IANGLE'), taper = one('TAPERANGLE'), starts = one('START COUNT');
  const tap = angle === 60;
  libs.push({id:f.slice(0, -3).toLowerCase().replace(/[^a-z0-9]+/g, '-'), name:f.slice(0, -3), libname:h.LIBNAME,
    unit:h.LIBUNITS ? 'in' : 'mm', pitch:'mm', angle, incl, taper, starts, tap,
    rows:rows.map(x => { const a = [x.NAME.trim(), x['BASIC MAJOR'], x['BOTTOM DIAMETER'], x.LEAD];
      if(tap) a.push(r(x['BASIC MAJOR'] - x.LEAD, 3)); return a; })});
}

const head = '/* Thread libraries — generated by tools/threads-export.js, do not edit by hand.\n' +
  '   ENCY samples (Libraries/Threads/Examples/*.db) + Unified inch (ASME B1.1). Row: [name, major Ø, minor Ø,\n' +
  '   pitch (mm, or TPI when pitch:"tpi"), tap drill (when tap)]. */\n';
fs.writeFileSync(OUT, head + 'window.ENCY_THREAD_LIBS = [\n' + libs.map(l => {
  const {rows, ...meta} = l;
  return ' ' + JSON.stringify(meta).slice(0, -1) + ',"rows":[\n' + rows.map(x => '  ' + JSON.stringify(x)).join(',\n') + ']}';
}).join(',\n') + '\n];\n');
console.log(libs.map(l => l.name + ': ' + l.rows.length).join('\n'), '\n→', OUT, fs.statSync(OUT).size, 'bytes');
